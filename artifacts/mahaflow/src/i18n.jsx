const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    const stored = window.localStorage.getItem("mahaflow-language");
    return messages[stored] ? stored : "en";
  });

  const setLanguage = (nextLanguage) => {
    if (!messages[nextLanguage]) return;
    setLanguageState(nextLanguage);
    window.localStorage.setItem("mahaflow-language", nextLanguage);
    document.documentElement.lang = nextLanguage === "hi" ? "hi" : nextLanguage === "mr" ? "mr" : "en";
  };

  const value = useMemo(() => ({
    language,
    setLanguage,
    t: (key) => messages[language][key] || messages.en[key] || key,
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
}